"""Round-4 tables and figures from data/processed/r4_ctx/runs/*.pkl (written by run_r4.py).

Outputs (results/r4_ctx/): summary.csv (every panel x mode x B x rule), spend_check.csv (per-replicate spend
verification), primary.csv (the pre-specified contrast), tables.md, figures/*.pdf.
Rows matched in < 80% of (replicate, split) cells are not estimable: their values are blanked (n.e.) in
tables.md and figures; summary.csv keeps the numbers with an `estimable` flag.

    unset VIRTUAL_ENV; uv run python tracks/r4_ctx/make_report.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT / "tracks" / "t2_per_context"))
import plotstyle as S  # noqa: E402
import r4lib as X  # noqa: E402
from run_r4 import JOBS, RUNS  # noqa: E402

OUT = ROOT / "results" / "r4_ctx"
FIG = OUT / "figures"
NOM = ["nom_spend", "nom_tpr_uniform", "nom_sel_informed"]
RULE_COLOR = {"global": S.SERIES[0], "cfar": S.SERIES[1], "pooled": S.SERIES[3], "stack": S.SERIES[6],
              "stack_m0": S.SERIES[4], "stack_sev": S.SERIES[5]}
RULE_LABEL = {"global": "Global", "cfar": "CFAR", "pooled": "Partial pooling (EB n0)",
              "stack": "Stackelberg, equal damage (m0 = 10)", "stack_m0": "Stackelberg, unshrunk",
              "stack_sev": "Stackelberg, severity-weighted (m0 = 10)"}
PANEL_LABEL = {"akshn_setting": "7 settings, Gemini\n(328-1,396 honest / context)",
               "ca_setting_model": "ControlArena setting x agent\n(~250 honest / context)",
               "la_pub_env": "public LinuxArena env, gpt-5-nano\n(~217 honest / context)"}


def load_all() -> pd.DataFrame:
    parts = [pd.read_pickle(RUNS / f"{p}__{m}.pkl") for p, m in JOBS]
    return pd.concat(parts, ignore_index=True)


def spend_check(raw: pd.DataFrame) -> pd.DataFrame:
    g = raw.groupby(["panel", "mode", "B", "rule"])
    m = raw[raw.matched_ok]
    out = pd.DataFrame(dict(
        cells=g.size(), share_matched=g.matched_ok.mean(),
        max_abs_realized_minus_B=m.assign(d=(m.realized - m.B).abs()).groupby(
            ["panel", "mode", "B", "rule"]).d.max(),
        floor_mean=g.floor.mean(), floor_p05=g.floor.quantile(0.05), floor_p95=g.floor.quantile(0.95),
        nominal_spend_mean=g.nom_spend.mean(), nominal_spend_p05=g.nom_spend.quantile(0.05),
        nominal_spend_p95=g.nom_spend.quantile(0.95))).reset_index()
    return out


def ci(r, c, nd=2):
    if not r.estimable or not np.isfinite(r[c]):
        return "n.e."
    return f"{r[c]:.{nd}f} [{r[c + '_lo']:.{nd}f}, {r[c + '_hi']:.{nd}f}]"


def dci(r, c, nd=2):
    if r.rule == "global":
        return "–"
    if not r.contrast_estimable or not np.isfinite(r[c + "_d"]):
        return "n.e."
    return f"{r[c + '_d']:+.{nd}f} [{r[c + '_dlo']:+.{nd}f}, {r[c + '_dhi']:+.{nd}f}]"


def table(df, cols, heads):
    L = ["| " + " | ".join(heads) + " |", "|" + "---|" * len(heads)]
    for _, r in df.iterrows():
        L.append("| " + " | ".join(str(c(r)) if callable(c) else str(r[c]) for c in cols) + " |")
    return "\n".join(L) + "\n"


def main():
    S.setup()
    raw = load_all()
    summ = X.summarize(raw, ["panel", "mode", "B"], X.METRICS + NOM)
    summ.to_csv(OUT / "summary.csv", index=False, float_format="%.4g")
    sc = spend_check(raw)
    sc.to_csv(OUT / "spend_check.csv", index=False, float_format="%.4g")
    bad = sc.max_abs_realized_minus_B.dropna()
    assert (bad <= 1e-6).all(), "a matched replicate does not spend exactly B"

    order = {r: i for i, r in enumerate(X.RULES)}
    summ["o"] = summ.rule.map(order)
    summ = summ.sort_values(["panel", "mode", "B", "o"])
    prim = summ[(summ.panel == "akshn_setting") & (summ["mode"] == "indist") & (summ.B == 0.01)
                & (summ.rule.isin(["global", "stack"]))]
    prim.to_csv(OUT / "primary.csv", index=False, float_format="%.4g")
    p = prim[prim.rule == "stack"].iloc[0]
    g = prim[prim.rule == "global"].iloc[0]

    md = ["# T2 round 4: per-context allocation at B = 1% with many honest runs per context "
          "(generated by tracks/r4_ctx/make_report.py)\n",
          "Design pre-specified in EXPERIMENT_LOG.md (2026-10-22, round 4). 10 grouped splits x 200 joint "
          "cluster-bootstrap replicates (+ the unweighted splits for point estimates). Spend matching is exact: "
          "the two fits bracketing B on the test honest runs are mixed into a randomized policy that spends "
          "exactly B (max |realized − B| over all matched replicates: "
          f"{bad.max():.1e}). Unmatched replicates (spend floor > B) are NaN, never clamped; rows matched in "
          "< 80% of cells are n.e. Intervals: 95% percentile over replicates of the split-average; Δ = paired "
          "difference vs global on cells where both are matched.\n",
          "## Primary contrast (pre-specified)\n",
          f"`akshn_setting`, in-distribution, B = 1%, spend-matched, selection safety against the informed "
          f"context-selecting attacker (information disjoint from the defender's fit):\n\n"
          f"- global {g.sel_informed:.3f} [{g.sel_informed_lo:.3f}, {g.sel_informed_hi:.3f}] (matched "
          f"{g.share_matched:.3f})\n"
          f"- Stackelberg (equal damage, m0 = 10) {p.sel_informed:.3f} [{p.sel_informed_lo:.3f}, "
          f"{p.sel_informed_hi:.3f}] (matched {p.share_matched:.3f})\n"
          f"- **Δ = {p.sel_informed_d:+.3f} [{p.sel_informed_dlo:+.3f}, {p.sel_informed_dhi:+.3f}]**, "
          f"P(Δ > 0) = {p.sel_informed_dpos:.3f}, both matched in {p.share_both_matched:.3f} of cells. "
          f"Pre-specified criterion (lower bound > 0, matched ≥ 80%): "
          f"{'MET' if p.sel_informed_dlo > 0 and p.share_both_matched >= 0.8 else 'NOT MET'}.\n"]
    pr = raw[(raw.panel == "akshn_setting") & (raw["mode"] == "indist") & (raw.B == 0.01)]
    pv = pr.pivot_table(index=["rep", "split"], columns="rule", values="sel_informed")
    dd = (pv["stack"] - pv["global"])
    rep = dd[dd.index.get_level_values(0) >= 0].groupby(level=0).mean()
    spl = dd[dd.index.get_level_values(0) < 0]
    q = rep.quantile([0.025, 0.975]).values
    md.append(f"Robustness of the primary interval: replicate mean {rep.mean():+.3f}; basic (reflected) bootstrap "
              f"interval [{2 * p.sel_informed_d - q[1]:+.3f}, {2 * p.sel_informed_d - q[0]:+.3f}]; per-split "
              f"point differences range {spl.min():+.3f} to {spl.max():+.3f} ({int((spl > 0).sum())}/{len(spl)} "
              f"splits > 0).\n")

    md.append("## Panels\n")
    pn = pd.read_csv(OUT / "panels.csv")
    pn = pn[pn.panel.isin(PANEL_LABEL)]
    md.append(table(pn, ["panel", "ctx", "n_honest", "n_attack", "honest_groups", "attack_groups",
                         lambda r: "task" if r.grouped_by_task else "trajectory", "side_tasks", "policies"],
                    ["panel", "context", "honest", "attacks", "honest groups", "attack groups", "split unit",
                     "side tasks", "attack policies"]))

    md.append("## Spend floor and nominal over-spend\n")
    md.append("Floor = realized test spend with every threshold at the top of its calibration data (mean and "
              "95th percentile over cells); a rule is matchable at B only where the floor is ≤ B. Nominal = "
              "realized test spend when the rule is fit at level B.\n")
    f = sc[(sc["mode"] == "indist")].copy()
    f["o"] = f.rule.map(order)
    f = f.sort_values(["panel", "B", "o"])
    md.append(table(f, ["panel", lambda r: f"{100 * r.B:g}%", "rule", lambda r: f"{r.share_matched:.2f}",
                        lambda r: f"{100 * r.floor_mean:.2f}% / {100 * r.floor_p95:.2f}%",
                        lambda r: f"{100 * r.nominal_spend_mean:.2f}% [{100 * r.nominal_spend_p05:.2f}, "
                                  f"{100 * r.nominal_spend_p95:.2f}]"],
                    ["panel", "B", "rule", "share matched", "floor mean / p95", "nominal spend [5-95%]"]))

    for mode, title in [("indist", "In-distribution attacks"),
                        ("indist_iid", "Sensitivity: iid (ungrouped) splits"),
                        ("xfer_side", "Transfer: defender fits on other side tasks"),
                        ("xfer_policy", "Transfer: defender fits on other attack policies / agent models")]:
        t = summ[summ["mode"] == mode]
        if not len(t):
            continue
        md.append(f"## {title} (spend-matched)\n")
        md.append("`sel` = selection safety vs the informed context-selecting attacker; `probe5` = vs an attacker "
                  "with 5 free alarm-feedback probes per context; `dmg_sel` = 1 − expected undetected damage / 10 "
                  "in the context a damage-maximizing attacker picks; `unif` = mean TPR over contexts (uniform "
                  "attacker); `oracle` = min test TPR (biased low).\n")
        md.append(table(t, ["panel", lambda r: f"{100 * r.B:g}%", "rule", lambda r: f"{r.share_matched:.2f}",
                            lambda r: ci(r, "tpr_uniform"), lambda r: ci(r, "sel_informed"),
                            lambda r: dci(r, "sel_informed"), lambda r: ci(r, "probe5"),
                            lambda r: dci(r, "probe5"), lambda r: ci(r, "dmg_informed"),
                            lambda r: dci(r, "dmg_informed"), lambda r: ci(r, "sel_oracle")],
                        ["panel", "B", "rule", "matched", "unif", "sel", "Δ sel vs global", "probe5",
                         "Δ probe5", "dmg_sel", "Δ dmg_sel", "oracle"]))
    (OUT / "tables.md").write_text("\n".join(md))
    figures(summ, sc)
    print("\n".join(md[:5]))


def figures(summ, sc):
    import matplotlib.pyplot as plt
    rules = ["cfar", "pooled", "stack", "stack_m0", "stack_sev"]
    # 1. Δ selection safety vs global by budget, one panel per data panel (in-distribution)
    panels = list(PANEL_LABEL)
    fig, axes = plt.subplots(1, 3, figsize=(7.4, 3.0), sharey=True)
    for ax, pn in zip(axes, panels):
        t = summ[(summ.panel == pn) & (summ["mode"] == "indist")]
        for j, r in enumerate(rules):
            d = t[t.rule == r].sort_values("B")
            xs = np.arange(len(d)) + (j - 2) * 0.12
            ok = d.contrast_estimable.values
            y = np.where(ok, d.sel_informed_d.values, np.nan)
            lo = np.where(ok, d.sel_informed_dlo.values, np.nan)
            hi = np.where(ok, d.sel_informed_dhi.values, np.nan)
            ax.errorbar(xs, y, yerr=[y - lo, hi - y], fmt="o", ms=3.5, lw=1.0, capsize=0,
                        color=RULE_COLOR[r], label=RULE_LABEL[r] if pn == panels[0] else None)
            for x_, o in zip(xs, ok):
                if not o:
                    ax.text(x_, -0.02, "n.e.", rotation=90, fontsize=5.5, color=S.INK2, ha="center", va="top")
        ax.axhline(0, color=S.INK2, lw=0.8)
        ax.set_xticks(range(4))
        ax.set_xticklabels(["0.5%", "1%", "2%", "5%"])
        ax.set_title(PANEL_LABEL[pn], fontsize=7.5)
    axes[1].set_xlabel("audit budget B (exactly spend-matched)")
    axes[0].set_ylabel("Δ selection safety vs global")
    fig.legend(loc="lower center", ncol=3, bbox_to_anchor=(0.5, -0.17))
    S.save(fig, FIG / "delta_selection_by_budget.pdf")

    # 2. spend floor vs budget: share of cells matchable, per rule and panel
    fig, axes = plt.subplots(1, 3, figsize=(7.4, 2.9), sharey=True)
    lab2 = {"global": "Global", "pooled": "Partial pooling (EB n0)",
            "cfar": "CFAR and all Stackelberg variants (same floor)"}
    for ax, pn in zip(axes, panels):
        t = sc[(sc.panel == pn) & (sc["mode"] == "indist")]
        for j, r in enumerate(["global", "pooled", "cfar"]):
            d = t[t.rule == r].sort_values("B")
            ax.plot(np.arange(len(d)) + (j - 1) * 0.06, d.share_matched, "-o", ms=3.5, color=RULE_COLOR[r],
                    label=lab2[r] if pn == panels[0] else None)
        ax.axhline(0.8, color=S.INK2, lw=0.8, ls="--")
        ax.set_xticks(range(4))
        ax.set_xticklabels(["0.5%", "1%", "2%", "5%"])
        ax.set_title(PANEL_LABEL[pn], fontsize=7.5)
    axes[1].set_xlabel("audit budget B")
    axes[0].set_ylabel("share of cells spend-matchable\n(dashed: 0.8 estimability cut)")
    fig.legend(loc="lower center", ncol=3, bbox_to_anchor=(0.5, -0.1))
    S.save(fig, FIG / "matchable_share.pdf")

    # 3. transfer at 1% and 5%: selection safety of global and Stackelberg variants by mode (primary panel)
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.5), sharey=True)
    modes = [("indist", "in-distribution"), ("xfer_side", "unseen\nside tasks"),
             ("xfer_policy", "unseen attack\npolicies")]
    for ax, B in zip(axes, (0.01, 0.05)):
        for j, r in enumerate(["global", "stack", "stack_m0", "stack_sev"]):
            for i, (m, _) in enumerate(modes):
                d = summ[(summ.panel == "akshn_setting") & (summ["mode"] == m) & (summ.B == B) & (summ.rule == r)]
                if not len(d) or not d.estimable.iloc[0]:
                    continue
                d = d.iloc[0]
                x = i + (j - 1.5) * 0.15
                ax.errorbar([x], [d.sel_informed], yerr=[[d.sel_informed - d.sel_informed_lo],
                                                        [d.sel_informed_hi - d.sel_informed]],
                            fmt="o", ms=3.5, lw=1.0, color=RULE_COLOR[r],
                            label=RULE_LABEL[r] if (i == 0 and B == 0.01) else None)
        ax.set_xticks(range(3))
        ax.set_xticklabels([lab for _, lab in modes])
        ax.set_title(f"7 settings, B = {100 * B:g}% (spend-matched)", fontsize=8)
    axes[0].set_ylabel("selection safety (informed attacker)")
    fig.legend(loc="lower center", ncol=2, bbox_to_anchor=(0.5, -0.2))
    S.save(fig, FIG / "transfer_selection.pdf")


if __name__ == "__main__":
    main()
