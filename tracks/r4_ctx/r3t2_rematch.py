"""Corrected r3_t2 (Watcher tiers) tables without the clamping spend matcher (audit2 m9 / C1 follow-up).

tracks/r3_t2/watcher_eval.py matched spend with r2lib.nominal_and_matched, which swept the level over
B x (0.3..2) and np.interp CLAMPED when the realized test spend never reached B. This re-runs the same
evaluation (same panels, rules, splits, seeds and replicate counts) with a non-clamping matcher:
  * level swept over B x {0, log-spaced 0.01..3, 1} (tracks/fixes/e5/e5fix_lib.LEVEL_MULTS);
  * metrics interpolated at realized test spend = B ONLY if B lies inside that replicate's realized-spend
    range; otherwise every matched metric is NaN (matched_ok = False). No clamping.
The r3_t2 files are not touched: outputs go to results/r4_ctx/r3t2_corrected/ and
data/processed/r4_ctx/r3t2_runs/. Rows whose share of matched replicates is < 0.8 are marked not estimable.

    unset VIRTUAL_ENV; uv run python tracks/r4_ctx/r3t2_rematch.py
"""
from __future__ import annotations

import sys
import time
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tracks" / "r3_t2"))
sys.path.insert(0, str(ROOT / "tracks" / "r2_t2"))
import r2lib as R  # noqa: E402
import watcher_eval as WE  # noqa: E402

OUT = ROOT / "results" / "r4_ctx" / "r3t2_corrected"
RAW = ROOT / "data" / "processed" / "r4_ctx" / "r3t2_runs"
MULTS = tuple(sorted(set([0.0, 1.0] + list(np.round(np.logspace(-2, np.log10(3.0), 30), 6)))))


def nominal_and_matched_noclamp(fit, evalf, B: float, mults=MULTS):
    res = []
    for m in mults:
        try:
            res.append(evalf(fit(B * m)))
        except Exception:  # noqa: BLE001  (a level the policy cannot realize)
            res.append(None)
    i1 = list(mults).index(1.0)
    out = [("nominal", dict(res[i1][0], matched_ok=True), res[i1][1])]
    ok_res = [r for r in res if r is not None]
    sp = np.array([r[0]["spend"] for r in ok_res], float)
    fin = np.isfinite(sp)
    matched = bool(fin.any() and sp[fin].min() <= B + 1e-12 and sp[fin].max() >= B - 1e-12)
    mt = {}
    for k in ok_res[0][0]:
        if not matched:
            mt[k] = np.nan
            continue
        y = np.array([r[0][k] for r in ok_res], float)
        g = fin & np.isfinite(y)
        o = np.argsort(sp[g], kind="stable")
        xs, ys = sp[g][o], y[g][o]
        mt[k] = float(np.interp(B, xs, ys)) if len(xs) and xs.min() <= B + 1e-12 and xs.max() >= B - 1e-12 \
            else np.nan
    mt["spend"] = B if matched else np.nan
    mt["matched_ok"] = matched
    out.append(("matched", mt, {}))
    return out


def run_patched(args):
    WE.R.nominal_and_matched = nominal_and_matched_noclamp
    return WE.run(args)


def summarize(raw: pd.DataFrame) -> pd.DataFrame:
    keys = ["panel", "B", "mode", "rule"]
    s = R.summarize(raw, keys, WE.METRICS)
    sh = raw.groupby(keys).matched_ok.mean().rename("share_matched").reset_index()
    s = s.drop(columns=["matched_ok"]).merge(sh, on=keys)
    # paired differences on replicates where both rules matched (R.summarize already drops NaN pairs);
    # count them
    b = raw[(raw.kind == "boot") & (raw["mode"] == "matched")]
    g = b[b.rule == "global"][["panel", "B", "rep", "matched_ok"]]
    m = b.merge(g, on=["panel", "B", "rep"], suffixes=("", "_ref"))
    both = (m.matched_ok & m.matched_ok_ref).groupby([m.panel, m.B, m.rule]).mean().rename(
        "share_both_matched_boot").reset_index()
    both["mode"] = "matched"
    s = s.merge(both, on=["panel", "B", "mode", "rule"], how="left")
    s["estimable"] = np.where(s["mode"] == "matched", s.share_matched >= 0.8, True)
    return s


def fmt(r, c):
    if not r.estimable:
        return "n.e."
    return R.fmt_ci(r[c], r.get(c + "_lo"), r.get(c + "_hi"))


def dfmt(r, c):
    if not r.estimable or not np.isfinite(r.get(c + "_d", np.nan)) or r.rule == "global":
        return "–" if r.rule == "global" else ("n.e." if not r.estimable else "–")
    return R.fmt_ci(r[c + "_d"], r[c + "_dlo"], r[c + "_dhi"])


def tables(s: pd.DataFrame) -> str:
    order = {r: i for i, r in enumerate(["global", "cfar", "watcher_perm", "watcher_strict", "tier_w", "tier_opt",
                                         "sev_tilt", "stack", "stack_sev", "mm_cell_sev", "tilt_mm"])}
    m = s[s["mode"] == "matched"].copy()
    m["o"] = m.rule.map(order)
    m = m.sort_values(["panel", "B", "o"])
    L = ["# r3_t2 Watcher tables, corrected spend matching (generated by tracks/r4_ctx/r3t2_rematch.py)\n",
         "Same panels, rules, seeds and replicate counts as `results/r3_t2/tables.md` (40 plain + 100 bootstrap "
         "replicates). Spend matched WITHOUT clamping: level swept over B x {0, 0.01..3}; a replicate's matched "
         "metrics are NaN unless B lies inside its realized-spend range. `matched` = share of all replicates "
         "matched; rows with matched < 0.80 are not estimable (n.e.) and their values are not shown. Δ = paired "
         "bootstrap difference vs global on replicates where both are matched.\n",
         "| panel | B | rule | matched | dmg_unif [95%] | dmg_org [95%] | Δ org vs global | dmg_cell [95%] | "
         "Δ cell vs global | uniform TPR | feasible |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in m.iterrows():
        tp = f"{r.tpr_uniform:.2f}" if r.estimable and np.isfinite(r.tpr_uniform) else "n.e."
        fe = f"{r.feasible:.2f}" if np.isfinite(r.feasible) else "–"
        L.append(f"| {r.panel} | {r.B:g} | {r.rule} | {r.share_matched:.2f} | {fmt(r, 'dmg_uniform')} | "
                 f"{fmt(r, 'dmg_org')} | {dfmt(r, 'dmg_org')} | {fmt(r, 'dmg_cell')} | {dfmt(r, 'dmg_cell')} | "
                 f"{tp} | {fe} |")
    return "\n".join(L) + "\n"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    names = "mb_mini,mb_mini@sidetask,mb_mini_full,mb_strong,mb_strong@sidetask,akshn_adj".split(",")
    n_plain, n_boot, chunks = 40, 100, 4
    jobs = []
    for i, n in enumerate(names):  # identical job list and seeds to watcher_eval.main
        for k in range(chunks):
            jobs.append((n, (0.01, 0.05), int(np.ceil(n_plain / chunks)), int(np.ceil(n_boot / chunks)),
                         20000 + 100 * i + k))
    t0 = time.time()
    parts = []
    with ProcessPoolExecutor(12) as ex:
        for j, r in zip(jobs, ex.map(run_patched, jobs)):
            r["rep"] = r["rep"] + 1000 * (j[4] % 100)
            parts.append(r)
            print(j[0], len(r), f"{time.time() - t0:.0f}s", flush=True)
    raw = pd.concat(parts, ignore_index=True)
    raw.to_parquet(RAW / "watcher_noclamp.parquet")
    s = summarize(raw)
    s.to_csv(OUT / "watcher_summary_noclamp.csv", index=False, float_format="%.4g")
    (OUT / "tables_noclamp.md").write_text(tables(s))
    print(s[s["mode"] == "matched"].pivot_table(index=["panel", "B"], columns="rule",
                                                values="share_matched").round(2).to_string())


if __name__ == "__main__":
    main()
