"""Audit issue m11: results/r3_t2/tables.md shows the akshn_adj panel (watcher_strict / sev_tilt at
0.98-0.99) without the label-leakage caveat that is only in EXPERIMENT_LOG.md.

Writes a corrected copy results/fixes/r3_t2/tables_annotated.md (the original is not modified): a
caveat note at the top, and a caveat blockquote at the head of every section that contains
akshn_adj rows. No numbers are changed.

    unset VIRTUAL_ENV; uv run python tracks/fixes/e5/m11_annotate_r3t2.py
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "results" / "r3_t2" / "tables.md"
DST = ROOT / "results" / "fixes" / "r3_t2" / "tables_annotated.md"

CAVEAT = (
    "> **Label-leakage caveat (akshn_adj rows).** The akshn_adj severity is aksh-n's outcome-adjudicated "
    "`overall_severity`, assigned with knowledge of whether the trajectory is an attack (honest runs 97% tier 1-3, "
    "attacks 87% tier >= 7; severity AUROC 0.998). It is not something a deployed rater can see. Every akshn_adj "
    "result that uses severity (watcher_perm / watcher_strict, tier_w / tier_opt, sev_tilt, stack_sev, mm_cell_sev, "
    "tilt_mm, and the severity-tier composition) is a label-leaking upper bound, not an achievable operating point. "
    "The blind severity rater used for the mb_* panels (no side task, no reasoning) gives severity AUROC 0.53-0.54. "
    "The suspicion-only rules on akshn_adj (global, cfar, stack) do not use severity for thresholding but are "
    "evaluated with the adjudicated damage weights.")

HEAD_NOTE = (
    "> Annotated copy of results/r3_t2/tables.md (audit issue m11; generated by "
    "tracks/fixes/e5/m11_annotate_r3t2.py). Numbers are unchanged; caveats were added to the sections that contain "
    "akshn_adj rows.\n")


def main():
    lines = SRC.read_text().splitlines()
    # section boundaries
    heads = [i for i, l in enumerate(lines) if l.startswith("## ")] + [len(lines)]
    out = lines[: heads[0]] + [HEAD_NOTE]
    for a, b in zip(heads[:-1], heads[1:]):
        sec = lines[a:b]
        out.append(sec[0])
        if any(l.startswith("| akshn_adj") for l in sec):
            out += ["", CAVEAT]
        out += sec[1:]
    DST.parent.mkdir(parents=True, exist_ok=True)
    DST.write_text("\n".join(out) + "\n")
    print("wrote", DST)


if __name__ == "__main__":
    main()
