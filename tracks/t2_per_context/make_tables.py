"""Markdown tables for the T2 report (results/t2/tables.md) from the result CSVs.

    unset VIRTUAL_ENV; uv run python tracks/t2_per_context/make_tables.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parents[2] / "results" / "t2"
MAIN = ["la_env_local", "la_env_cum", "la_taskcat_local", "la_model_local", "akshn_setting",
        "ca_setting_model", "mb_gpt-4.1-mini_full", "mb_gpt-4.1-mini_none", "mb_gpt-4.1-nano_none",
        "mb_gpt-4.1-mini_trajectory", "mb_gpt-4.1-nano_trajectory"]
RULES = ["global", "cfar", "mondrian", "pooled_eb", "pooled_cv", "maxdet", "stackelberg",
         "stackelberg_dw", "os_shift", "tm_scale"]


def md(df: pd.DataFrame, floatfmt="{:.3f}") -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, (float, np.floating)) else str(v)
                                     for v in r.values) + " |")
    return "\n".join(out)


def ci(row, m, pct=False):
    s = 100 if pct else 1
    v, lo, hi = row[m] * s, row[m + "_lo"] * s, row[m + "_hi"] * s
    return f"{v:.2f} [{lo:.2f}, {hi:.2f}]" if pct else f"{v:.3f} [{lo:.2f}, {hi:.2f}]"


def dci(row, m):
    return f"{row[m + '_dlo']:+.2f}..{row[m + '_dhi']:+.2f}"


def main():
    parts = ["# T2 tables (generated by tracks/t2_per_context/make_tables.py)\n"]
    het = pd.read_csv(OUT / "heterogeneity.csv")
    h = het[["panel", "n_ctx", "n_honest", "min_n_honest", "auroc_pooled", "icc_max", "icc_max_ns",
             "step_share_ctx", "fpr_min@0.01", "fpr_max@0.01", "fpr_min@0.05", "fpr_max@0.05",
             "tau_logit@0.05", "tau_p@0.05", "tau_logit@0.1", "spend_tv@0.05", "eb_n0"]].copy()
    for c in ["fpr_min@0.01", "fpr_max@0.01", "fpr_min@0.05", "fpr_max@0.05"]:
        h[c] = (h[c] * 100).round(1)
    h = h.round(3)
    parts.append("## Heterogeneity of honest trajectory-max scores by context\n\n"
                 "ICC = between-context share of variance of the honest trajectory max (raw / normal "
                 "scores); step_share_ctx = context share of per-step score variance (nested ANOVA); "
                 "fpr_min/max = realized per-context FPR (%) under one global threshold at 1% / 5% "
                 "(in-sample); tau = SD of logit per-context FPR at the global 5% / 10% threshold, net "
                 "of binomial noise (logit-normal random effects; p = LR test of tau = 0); spend_tv = "
                 "total-variation distance between audit-spend shares and traffic shares at 5%; eb_n0 = "
                 "empirical-Bayes prior strength (large = homogeneous).\n\n" + md(h, "{}") + "\n")
    cons = pd.read_csv(OUT / "lasweep_monitor_consistency.csv", index_col=0)
    parts.append("## Are the same environments hot for every monitor? (LinuxArena sweep)\n\n"
                 + md(cons.reset_index().rename(columns={"index": "stat"}), "{:.3f}") + "\n")

    files = sorted(OUT.glob("allocation_summary_full_*.csv"))
    al = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    al = al[al.ncal == -1]
    for B, mode, note in [(0.01, "nominal", "as deployed (each rule at its nominal budget)"),
                          (0.05, "matched", "spend-matched (metrics interpolated at realized test spend = B)"),
                          (0.01, "matched", "spend-matched")]:
        rows = []
        for pn in MAIN:
            d = al[(al.panel == pn) & (al.B == B) & (al["mode"] == mode)]
            if d.empty:
                continue
            for r in RULES:
                x = d[d.rule == r]
                if x.empty:
                    continue
                x = x.iloc[0]
                rows.append(dict(panel=pn, rule=r,
                                 spend_pct=ci(x, "spend", True) if mode == "nominal" else f"{x['spend'] * 100:.2f}",
                                 matched_ok=f"{x.get('matched_ok', np.nan):.2f}" if mode == "matched" else "",
                                 tpr_uniform=ci(x, "tpr_uniform"),
                                 d_tpr_vs_global=dci(x, "tpr_uniform") if r != "global" else "",
                                 sel_informed=ci(x, "sel_informed"),
                                 d_sel_vs_global=dci(x, "sel_informed") if r != "global" else "",
                                 sel_oracle=f"{x['sel_oracle']:.3f}", dmg_informed=f"{x['dmg_informed']:.3f}",
                                 cell_informed=f"{x['cell_informed']:.3f}"))
        parts.append(f"## Allocation at B = {B:.0%}, {note}\n\nPoint = mean over 60 plain 50/50 "
                     "splits; [95% interval] and paired differences vs global = percentiles over 150 "
                     "split-then-bootstrap replicates. sel_informed = TPR in the context an informed "
                     "attacker picks; sel_oracle = min test TPR over contexts; dmg_informed = 1 - "
                     "damage-weighted payoff of the informed attacker (D_c ~ logU[1,10]); cell_informed "
                     "= informed attacker over (context, attack type) cells. matched_ok = share of "
                     "replicates where the nominal-level sweep brackets the target spend (values with "
                     "matched_ok < 0.8 are extrapolated and should not be compared).\n\n"
                     + md(pd.DataFrame(rows), "{}") + "\n")
    # lasweep / mrt (small n per context)
    sm = al[al.panel.str.startswith(("lasweep_", "mrt_")) & (al["mode"] == "nominal")]
    for B in (0.01, 0.05):
        t = sm[sm.B == B].pivot_table(index="panel", columns="rule", values="spend")[
            ["global", "cfar", "mondrian", "pooled_eb", "pooled_cv", "maxdet", "stackelberg"]] * 100
        parts.append(f"## Realized spend (%) at nominal B = {B:.0%} with 10 honest calibration runs per "
                     "context (LinuxArena sweep, MRT)\n\n" + md(t.round(2).reset_index(), "{}") + "\n")
        t = sm[sm.B == B].pivot_table(index="panel", columns="rule", values="tpr_uniform")[
            ["global", "cfar", "pooled_eb", "pooled_cv", "maxdet", "stackelberg"]]
        parts.append(f"TPR (uniform attacker) at nominal B = {B:.0%} (per-context rules overspend, see above)\n\n"
                     + md(t.round(3).reset_index(), "{}") + "\n")
    # small sample
    ss = pd.concat([pd.read_csv(f) for f in files], ignore_index=True)
    ss = ss[(ss["mode"] == "nominal") & (ss.B == 0.01) &
            ss.panel.isin(["la_env_local", "akshn_setting", "ca_setting_model", "la_taskcat_local"]) &
            ss.rule.isin(["global", "cfar", "mondrian", "pooled_eb", "pooled_cv"])]
    rows = []
    for (pn, nc), d in ss.groupby(["panel", "ncal"]):
        r = dict(panel=pn, n_cal_per_ctx=("all" if nc == -1 else int(nc)))
        for rule in ["global", "cfar", "mondrian", "pooled_eb", "pooled_cv"]:
            x = d[d.rule == rule]
            if len(x):
                x = x.iloc[0]
                r[rule] = f"{x['spend'] / 0.01:.2f}x / {x['tpr_uniform']:.2f} / {x['sel_informed']:.2f}"
        rows.append(r)
    parts.append("## Small-sample regime, B = 1% (realized spend / B, uniform TPR, selection safety)\n\n"
                 + md(pd.DataFrame(rows), "{}") + "\n")
    # poisoning
    po = pd.read_csv(OUT / "poisoning_summary.csv")
    for poison in ("attack_max", "honest_max"):
        p = po[(po.poison == poison) & po.eps.isin([0, 0.01, 0.02, 0.05, 0.1, 0.2, 0.3])]
        t = p.pivot_table(index=["panel", "eps"], columns="rule", values="tpr_t")[
            ["global", "cfar", "pooled_eb", "os_shift", "tm_scale", "refmix", "frozen", "cap"]]
        parts.append(f"## One-shot poisoning ({poison}): TPR in the poisoned context, B = 1%\n\n"
                     "Mean over targets (every context) and 40 replicates.\n\n"
                     + md(t.round(3).reset_index(), "{}") + "\n")
    b = pd.read_csv(OUT / "boiling_frog_rounds.csv")
    last = b[b["round"] == b["round"].max()]
    t = last.pivot_table(index=["panel", "scenario", "eps"], columns="rule", values=["tpr_t", "fpr_t"])
    t.columns = [f"{a}:{c}" for a, c in t.columns]
    parts.append("## Boiling frog and genuine drift after 30 rounds (target context, B = 1%)\n\n"
                 + md(t.round(3).reset_index(), "{}") + "\n")
    (OUT / "tables.md").write_text("\n".join(parts))
    print("wrote", OUT / "tables.md")


if __name__ == "__main__":
    main()
