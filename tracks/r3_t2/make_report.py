"""Tables (results/r3_t2/tables.md) and vector-PDF figures for T2 round 3 (Watcher-like severity tiers).

    unset VIRTUAL_ENV; uv run python tracks/r3_t2/make_report.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tracks" / "r2_t2"))
sys.path.insert(0, str(ROOT / "tracks" / "t2_per_context"))
import plotstyle as S  # noqa: E402
import r2lib as R  # noqa: E402

plt = S.plt
OUT = ROOT / "results" / "r3_t2"
FIG = OUT / "figures"
RULES = [("global", "Global (suspicion only)"), ("cfar", "CFAR per org"),
         ("watcher_perm", "Watcher permissive (9-10 always, 7-8 if suspicious)"),
         ("watcher_strict", "Watcher strict (9-10 always, 4-8 if suspicious)"),
         ("tier_w", "Tier thresholds, FPR weights 0/1/3/10"), ("tier_opt", "Tier thresholds, tuned weights"),
         ("sev_tilt", "Global on suspicion + β·severity"), ("stack", "Stackelberg per org (equal damage)"),
         ("stack_sev", "Stackelberg per org (severity damage)"), ("mm_cell_sev", "Minimax (org × severity) cells"),
         ("tilt_mm", "Minimax cells on tilted score")]
COLORS = {r: S.SERIES[i % 8] for i, (r, _) in enumerate(RULES)}
MARKS = ["o", "s", "v", "^", "D", "P", "X", "<", ">", "h", "*"]
PANEL_LABEL = {"mb_mini": "BashArena, gpt-4.1-mini (history-free); damage = Watcher severity",
               "mb_mini@sidetask": "BashArena, gpt-4.1-mini; damage = side-task tier",
               "mb_mini_full": "BashArena, gpt-4.1-mini (history-aware); damage = Watcher severity",
               "mb_strong": "BashArena, gpt-4.1 (history-free); damage = Watcher severity",
               "mb_strong@sidetask": "BashArena, gpt-4.1; damage = side-task tier",
               "akshn_adj": "7 settings, outcome-adjudicated severity (label-leaking bound)"}
MD: list[str] = []
KEY = {"global", "cfar", "watcher_perm", "watcher_strict", "tier_opt", "sev_tilt", "stack_sev", "mm_cell_sev"}


def table(df, cols, header):
    MD.append("| " + " | ".join(header) + " |")
    MD.append("|" + "---|" * len(header))
    for _, r in df.iterrows():
        MD.append("| " + " | ".join(str(c(r)) if callable(c) else str(r[c]) for c in cols) + " |")
    MD.append("")


def ci(r, m):
    return R.fmt_ci(r[m], r.get(m + "_lo"), r.get(m + "_hi"))


def dci(r, m):
    d = r.get(m + "_d", np.nan)
    if not np.isfinite(d):
        return "–"
    return f"{d:+.2f} [{r[m + '_dlo']:+.2f}, {r[m + '_dhi']:+.2f}]"


def main():
    S.setup()
    MD.append("# T2 round 3: Watcher-like severity tiers (generated by tracks/r3_t2/make_report.py)\n")
    comp = pd.read_csv(OUT / "tier_composition.csv")
    MD.append("## Severity-tier composition of traffic\n")
    MD.append("Share of actions per Watcher tier (1-3 / 4-6 / 7-8 / 9-10), share of trajectories containing at "
              "least one action of the tier, mean attack damage, and trajectory-level AUROC of suspicion (max) "
              "and of severity (max) for attack vs honest.\n")
    table(comp, ["panel", "label", "n_traj", lambda r: f"{r.act_tier1:.2f}/{r.act_tier2:.2f}/{r.act_tier3:.2f}/{r.act_tier4:.3f}",
                 lambda r: f"{r.traj_has_tier2:.2f}/{r.traj_has_tier3:.2f}/{r.traj_has_tier4:.3f}",
                 lambda r: f"{r.dmg_mean:.2f}", lambda r: f"{r.auroc_susp:.3f}", lambda r: f"{r.auroc_sev:.3f}"],
          ["panel", "label", "trajectories", "action share by tier", "traj. has tier 4-6/7-8/9-10",
           "mean max severity", "AUROC suspicion", "AUROC severity"])
    s = pd.read_csv(OUT / "watcher_summary.csv")
    m = s[s["mode"] == "matched"].copy()
    m["o"] = m.rule.map({r: i for i, (r, _) in enumerate(RULES)})
    m = m.sort_values(["panel", "B", "o"])
    MD.append("## Policy comparison (spend-matched)\n")
    MD.append("`dmg_unif` = damage-weighted detection vs a uniform attacker; `dmg_org` = 1 − expected undetected "
              "damage / 10 in the org an informed attacker picks; `dmg_cell` = same when the attacker picks an "
              "(org, damage tier) cell (severity-aware attacker); Δ = paired bootstrap difference vs global. "
              "`feasible` = share of replicates where the policy can spend exactly B (tier gating can cap the "
              "reachable spend, the always-block tier can exceed it); `matched_ok` = B inside the swept range.\n")
    table(m, ["panel", "B", "rule", lambda r: f"{r.spend:.3f}", lambda r: ci(r, "dmg_uniform"),
              lambda r: ci(r, "dmg_org"), lambda r: dci(r, "dmg_org"), lambda r: ci(r, "dmg_cell"),
              lambda r: dci(r, "dmg_cell"), lambda r: f"{r.tpr_uniform:.2f}", lambda r: f"{r.feasible:.2f}",
              lambda r: f"{r.matched_ok:.2f}"],
          ["panel", "B", "rule", "spend", "dmg_unif [95%]", "dmg_org [95%]", "Δ org vs global", "dmg_cell [95%]",
           "Δ cell vs global", "uniform TPR", "feasible", "matched_ok"])
    nom = s[s["mode"] == "nominal"]
    MD.append("## Nominal-mode realized spend (B = 1% and 5%)\n")
    pv = nom.pivot_table(index=["panel", "B"], columns="rule", values="spend").round(3).reset_index()
    table(pv, list(pv.columns), list(pv.columns))
    (OUT / "tables.md").write_text("\n".join(MD))

    # figure 1: tier composition
    fig, ax = plt.subplots(figsize=(6.8, 2.6))
    pans = [("mb_mini", "BashArena (Watcher severity, gpt-4.1-mini rater)"),
            ("akshn_adj", "7 settings (outcome-adjudicated severity)")]
    xs = []
    lab = []
    k = 0
    for p, pl in pans:
        for lab_ in ("honest", "attack"):
            r = comp[(comp.panel == p) & (comp.label == lab_)].iloc[0]
            vals = [r.traj_has_tier2, r.traj_has_tier3, r.traj_has_tier4]
            for j, v in enumerate(vals):
                ax.bar(k + (j - 1) * 0.26, v, 0.24, color=[S.SERIES[0], S.SERIES[3], S.SERIES[7]][j],
                       label=["has a 4-6 action", "has a 7-8 action", "has a 9-10 action"][j] if k == 0 else None)
            xs.append(k)
            lab.append(f"{lab_}\n{pl.split(' (')[0]}")
            k += 1
    ax.set_xticks(xs)
    ax.set_xticklabels(lab, fontsize=7)
    ax.set_ylabel("share of trajectories")
    ax.set_ylim(0, 1.05)
    ax.legend(fontsize=7, ncol=3, loc="upper center", bbox_to_anchor=(0.5, 1.2))
    S.save(fig, FIG / "tier_composition.pdf")

    # figure 2: policies x panels, dmg_org and dmg_cell at B = 5% and 1%
    panels = [p for p in PANEL_LABEL if p in set(m.panel)]
    fig, axes = plt.subplots(len(panels), 2, figsize=(7.8, 1.25 * len(panels) + 1.2), sharex=True)
    for i, p in enumerate(panels):
        for j, B in enumerate((0.01, 0.05)):
            ax = axes[i, j]
            q = m[(m.panel == p) & (m.B == B)]
            for k, (r, rl) in enumerate([x for x in RULES if x[0] in KEY]):
                z = q[q.rule == r]
                if not len(z):
                    continue
                z = z.iloc[0]
                for yy, met in ((0, "dmg_unif"), (1, "dmg_org"), (2, "dmg_cell")):
                    col = {"dmg_unif": "dmg_uniform"}.get(met, met)
                    ax.plot(z[col], yy + (k - 3.5) * 0.08, MARKS[k], color=COLORS[r], ms=3.8,
                            mfc=COLORS[r] if z.feasible > 0.5 else "white", mec=COLORS[r], mew=0.8,
                            label=rl if (i, j) == (0, 0) and yy == 0 else None)
            ax.set_yticks([0, 1, 2])
            ax.set_yticklabels(["uniform", "org-select", "cell-select"], fontsize=6.5)
            ax.set_xlim(-0.02, 1.02)
            ax.invert_yaxis()
            ax.set_title(f"{PANEL_LABEL[p]} — B = {B:.0%}", fontsize=6.4, loc="left", color=S.INK2)
    for ax in axes[-1]:
        ax.set_xlabel("damage-weighted safety", fontsize=7.5)
    fig.legend(loc="lower center", ncol=2, fontsize=6.5, bbox_to_anchor=(0.5, -0.11))
    fig.tight_layout(h_pad=1.6)
    S.save(fig, FIG / "watcher_policies.pdf")
    print("wrote", OUT / "tables.md")


if __name__ == "__main__":
    main()
